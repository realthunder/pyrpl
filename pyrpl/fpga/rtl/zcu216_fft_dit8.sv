/**
 * Real-input FFT of N = 8 * 2^SUB points at 8 samples per clock (FFT_IMPL=6).
 *
 * xfft 9.1 stops at 64k points, and with super_sample_rates > 1 it forces natural
 * order output (a reorder buffer per core) and drops xk_index. So the transform is
 * split by decimation in time over the 8 input lanes instead: lane i carries
 * x[8m+i], which goes straight into its own 2^SUB-point xfft (xfft_sub: 1 sample
 * per clock, unscaled, bit-reversed output with xk_index). All eight cores run in
 * lockstep, so they emit the same bin k on the same cycle, and
 *
 *   X[k + q*2^SUB] = sum_i  W_N^(i*k) * W_8^(i*q) * Y_i[k]      (N = 8 * 2^SUB)
 *
 * is a streaming recombination: seven twiddle multiplies, then an 8-point DFT.
 * The input is real, so only q = 0..3 (bins 0 .. N/2-1) are formed: four bins per
 * clock, lane q holding bin k + q*2^SUB, in the cores' bit-reversed k order.
 *
 * Widths: a full-scale IN_W-bit tone gives |Y| < 2^(IN_W-1+SUB); Y is cut to DW
 * bits (dropping LSBs that sit far below the quantisation noise of a 2^SUB sum),
 * so the twiddle products fit one DSP48E2 (27 x 18) each. X is DW+5 bits.
 *
 * xfft_sub is generated by the build script (zcu216_vivado.tcl) with
 * transform_length 2^SUB; the twiddle tables come from zcu216/gen_tables.tcl.
 */

module zcu216_fft_dit8 #(
  parameter int    SUB      = 15,   // log2 of the sub-FFT size
  parameter int    IN_W     = 14,   // significant input bits (signed)
  parameter int    DW       = 27,   // sub-FFT output bits kept
  parameter int    TW       = 18,   // twiddle bits, Q1.(TW-1)
  parameter string TWC_FILE = "",
  parameter string TWF_FILE = "",
  localparam int   XW       = DW + 5
) (
  input  logic                 clk,
  input  logic                 rstn,
  output logic                 cfg_done,   // all cores have their config
  // 8 real samples per clock, sample 8b+i on lane i (a continuous source)
  input  logic [8*16-1:0]      in_data,
  input  logic                 in_valid,
  input  logic                 run,        // start/stop frames at a frame boundary
  output logic                 in_accept,  // this beat went into the FFT
  output logic                 in_first,   // ... and is the first beat of a frame
  // bin k + q*2^SUB on lane q
  output logic signed [XW-1:0] x_re [4],
  output logic signed [XW-1:0] x_im [4],
  output logic [SUB-1:0]       x_k,
  output logic                 x_valid,
  output logic                 x_last,
  // xfft events, OR-ed over the cores (one-cycle pulses)
  output logic                 ev_halt,
  output logic                 ev_tlast_unexpected,
  output logic                 ev_tlast_missing
);

localparam int NB   = SUB + 3;               // log2 N
localparam int OWR  = 16 + SUB + 1;          // xfft unscaled output width
localparam int OB   = (OWR + 7) / 8 * 8;     // byte-rounded component slot
localparam int UB   = (SUB + 7) / 8 * 8;     // tuser (xk_index) width
localparam int YW   = IN_W + SUB;            // bound on |Y|
localparam int DROP = (YW > DW) ? YW - DW : 0;
localparam int ZW   = DW + 1;

////////////////////////////////////////////////////////////////////////////////
// the eight sub-FFTs
////////////////////////////////////////////////////////////////////////////////

logic [7:0]      cfg_ok, cfg_tready, in_tready;
logic [2*OB-1:0] m_tdata [8];
logic [UB-1:0]   m_tuser [8];
logic [7:0]      m_tvalid, m_tlast, e_halt, e_unexp, e_miss;

// One config word (forward transform; unscaled has no schedule) per core after
// reset. A core that already took it may take it again: same value.
always_ff @(posedge clk)
  if (!rstn) cfg_ok <= '0;
  else       cfg_ok <= cfg_ok | cfg_tready;

assign cfg_done = &cfg_ok;

// Framing. A beat goes in only when every core is ready: a core drops
// s_axis_data_tready for a cycle inside its first frame, while it applies the
// config word, and a beat sent then is lost to it, shifting every later frame by
// one sample. So such beats are discarded here (the source is not stalled; it may
// be an ADC), and frames are counted in accepted beats: tlast is always the
// 2^SUB-th. Frames start and stop on a boundary, so a core never sees a partial
// frame (the realtime core would flag a halt and corrupt it).
logic           active, in_ready;
logic [SUB-1:0] beat;

assign in_ready  = &in_tready;
assign in_accept = active && in_valid && in_ready;
assign in_first  = in_accept && beat == '0;

always_ff @(posedge clk)
  if (!rstn) begin
    active <= 1'b0;
    beat   <= '0;
  end else if (!active) begin
    active <= run && cfg_done;
  end else if (in_accept) begin
    beat <= beat + 1'b1;
    if (&beat && !run) active <= 1'b0;
  end

for (genvar i = 0; i < 8; i++) begin : g_core
  xfft_sub i_xfft (
    .aclk                       (clk               ),
    .aresetn                    (rstn              ),
    .s_axis_config_tdata        (8'h01             ),
    .s_axis_config_tvalid       (!cfg_done         ),
    .s_axis_config_tready       (cfg_tready[i]     ),
    .s_axis_data_tdata          ({16'h0, in_data[16*i +: 16]}),
    .s_axis_data_tvalid         (active && in_valid),
    .s_axis_data_tready         (in_tready[i]      ),
    .s_axis_data_tlast          (&beat             ),
    .m_axis_data_tdata          (m_tdata[i]        ),
    .m_axis_data_tuser          (m_tuser[i]        ),
    .m_axis_data_tvalid         (m_tvalid[i]       ),
    .m_axis_data_tlast          (m_tlast[i]        ),
    .event_frame_started        (                  ),
    .event_tlast_unexpected     (e_unexp[i]        ),
    .event_tlast_missing        (e_miss[i]         ),
    .event_data_in_channel_halt (e_halt[i]         )
  );
end

always_ff @(posedge clk) begin
  ev_halt             <= |e_halt;
  ev_tlast_unexpected <= |e_unexp;
  ev_tlast_missing    <= |e_miss;
end

////////////////////////////////////////////////////////////////////////////////
// Y_i[k], cut to DW bits
////////////////////////////////////////////////////////////////////////////////

logic signed [DW-1:0] y_re [8], y_im [8];
logic [SUB-1:0]       y_k;
logic                 y_valid = 1'b0, y_last = 1'b0;

// rounded: round-half-up, so the cut adds no bias
localparam logic signed [OWR:0] YRND = (DROP > 0) ? (OWR+1)'(1) <<< (DROP-1) : '0;

always_ff @(posedge clk) begin
  for (int i = 0; i < 8; i++) begin
    y_re[i] <= DW'(($signed(m_tdata[i][0  +: OWR]) + YRND) >>> DROP);
    y_im[i] <= DW'(($signed(m_tdata[i][OB +: OWR]) + YRND) >>> DROP);
  end
  y_k     <= m_tuser[0][SUB-1:0];
  y_valid <= m_tvalid[0];
  y_last  <= m_tlast[0];
end

////////////////////////////////////////////////////////////////////////////////
// Z_i = Y_i * W_N^(i*k)
////////////////////////////////////////////////////////////////////////////////

localparam int TW_LAT = 7;                   // zcu216_twiddle
localparam int CM_LAT = 4;                   // zcu216_cmul
localparam int Z_LAT  = TW_LAT + CM_LAT;

logic signed [ZW-1:0] z_re [8], z_im [8];

// Z_0 = Y_0, delayed to line up
logic signed [DW-1:0] y0_re_d, y0_im_d;
zcu216_delay #(.W(2*DW), .D(Z_LAT)) i_dly_y0 (
  .clk, .d({y_re[0], y_im[0]}), .q({y0_re_d, y0_im_d}));
assign z_re[0] = ZW'(y0_re_d);
assign z_im[0] = ZW'(y0_im_d);

for (genvar i = 1; i < 8; i++) begin : g_tw
  logic signed [TW-1:0] w_re, w_im;
  logic signed [DW-1:0] yd_re, yd_im;

  // i*k < 7 * 2^SUB < 2^NB: no wrap
  zcu216_twiddle #(.NB(NB), .TW(TW), .C_FILE(TWC_FILE), .F_FILE(TWF_FILE)) i_tw (
    .clk, .a(NB'(i) * NB'(y_k)), .w_re, .w_im);

  zcu216_delay #(.W(2*DW), .D(TW_LAT)) i_dly (
    .clk, .d({y_re[i], y_im[i]}), .q({yd_re, yd_im}));

  zcu216_cmul #(.AW(DW), .BW(TW), .SHIFT(TW-1), .OW(ZW)) i_mul (
    .clk, .a_re(yd_re), .a_im(yd_im), .b_re(w_re), .b_im(w_im),
    .p_re(z_re[i]), .p_im(z_im[i]));
end

////////////////////////////////////////////////////////////////////////////////
// X_q = sum_i Z_i * W_8^(i*q), q = 0..3
////////////////////////////////////////////////////////////////////////////////

localparam int R8_LAT = 6;                   // zcu216_radix8_half

zcu216_radix8_half #(.ZW(ZW)) i_r8 (
  .clk, .z_re, .z_im, .x_re, .x_im);

zcu216_delay #(.W(SUB), .D(Z_LAT + R8_LAT)) i_dly_k (
  .clk, .d(y_k), .q(x_k));
zcu216_delay #(.W(2), .D(Z_LAT + R8_LAT)) i_dly_v (
  .clk, .d({y_valid, y_last}), .q({x_valid, x_last}));

endmodule


/**
 * (a_re + j a_im) * (b_re + j b_im), rounded and shifted right by SHIFT.
 * Four real multiplies, one DSP48E2 each for AW <= 27, BW <= 18. Latency 4.
 */
module zcu216_cmul #(
  parameter int AW = 27,
  parameter int BW = 18,
  parameter int SHIFT = 17,
  parameter int OW = AW + 1
) (
  input  logic                 clk,
  input  logic signed [AW-1:0] a_re, a_im,
  input  logic signed [BW-1:0] b_re, b_im,
  output logic signed [OW-1:0] p_re, p_im
);

logic signed [AW-1:0]    ar, ai;
logic signed [BW-1:0]    br, bi;
logic signed [AW+BW-1:0] m_rr, m_ii, m_ri, m_ir;
logic signed [AW+BW:0]   s_re, s_im;

localparam logic signed [AW+BW:0] RND = (AW+BW+1)'(1) <<< (SHIFT-1);

always_ff @(posedge clk) begin
  ar   <= a_re;  ai <= a_im;  br <= b_re;  bi <= b_im;
  m_rr <= ar * br;  m_ii <= ai * bi;
  m_ri <= ar * bi;  m_ir <= ai * br;
  s_re <= m_rr - m_ii + RND;
  s_im <= m_ri + m_ir + RND;
  p_re <= OW'(s_re >>> SHIFT);
  p_im <= OW'(s_im >>> SHIFT);
end

endmodule


/**
 * W = exp(-j*2*pi*a / 2^NB), Q1.(TW-1), from two small tables:
 * W = Wc[a >> L] * Wf[a & (2^L-1)]. Latency 7 (address, 2 ROM, 4 multiply).
 */
module zcu216_twiddle #(
  parameter int    NB = 18,
  parameter int    TW = 18,
  parameter string C_FILE = "",
  parameter string F_FILE = ""
) (
  input  logic                 clk,
  input  logic [NB-1:0]        a,
  output logic signed [TW-1:0] w_re, w_im
);

localparam int H = (NB + 1) / 2;
localparam int L = NB - H;

(* rom_style = "block" *) logic [2*TW-1:0] rom_c [0:(1<<H)-1];
(* rom_style = "block" *) logic [2*TW-1:0] rom_f [0:(1<<L)-1];

initial begin
  $readmemh(C_FILE, rom_c);
  $readmemh(F_FILE, rom_f);
end

logic [H-1:0]    ah;
logic [L-1:0]    al;
logic [2*TW-1:0] c0, c1, f0, f1;

always_ff @(posedge clk) begin
  ah <= a[NB-1 -: H];
  al <= a[L-1:0];
  c0 <= rom_c[ah];  c1 <= c0;
  f0 <= rom_f[al];  f1 <= f0;
end

logic signed [TW:0] p_re, p_im;

zcu216_cmul #(.AW(TW), .BW(TW), .SHIFT(TW-1), .OW(TW+1)) i_mul (
  .clk,
  .a_re(c1[0 +: TW]), .a_im(c1[TW +: TW]),
  .b_re(f1[0 +: TW]), .b_im(f1[TW +: TW]),
  .p_re, .p_im);

// |Wc * Wf| <= 1: the product fits TW bits
assign w_re = p_re[TW-1:0];
assign w_im = p_im[TW-1:0];

endmodule


/**
 * X_q = A_q + W_8^q * B_q for q = 0..3, where A = DFT4(Z0, Z2, Z4, Z6) and
 * B = DFT4(Z1, Z3, Z5, Z7): the lower half of an 8-point DFT. Latency 6.
 */
module zcu216_radix8_half #(
  parameter int  ZW = 28,
  localparam int XW = ZW + 4
) (
  input  logic                 clk,
  input  logic signed [ZW-1:0] z_re [8],
  input  logic signed [ZW-1:0] z_im [8],
  output logic signed [XW-1:0] x_re [4],
  output logic signed [XW-1:0] x_im [4]
);

localparam int CW = 18;
localparam logic signed [CW-1:0] C = 18'sd92682;   // round(2^17 / sqrt(2))

// stage 1: first DFT4 level, for the even (e) and odd (o) inputs
logic signed [ZW:0] s02_re [2], s02_im [2], d02_re [2], d02_im [2];
logic signed [ZW:0] s13_re [2], s13_im [2], d13_re [2], d13_im [2];

always_ff @(posedge clk)
  for (int p = 0; p < 2; p++) begin           // p = 0: Z0,2,4,6; p = 1: Z1,3,5,7
    s02_re[p] <= z_re[p] + z_re[p+4];  s02_im[p] <= z_im[p] + z_im[p+4];
    d02_re[p] <= z_re[p] - z_re[p+4];  d02_im[p] <= z_im[p] - z_im[p+4];
    s13_re[p] <= z_re[p+2] + z_re[p+6];  s13_im[p] <= z_im[p+2] + z_im[p+6];
    d13_re[p] <= z_re[p+2] - z_re[p+6];  d13_im[p] <= z_im[p+2] - z_im[p+6];
  end

// stage 2: DFT4 outputs, A = even, B = odd
//   out0 = s02 + s13, out1 = d02 - j d13, out2 = s02 - s13, out3 = d02 + j d13
logic signed [ZW+1:0] f_re [2][4], f_im [2][4];

always_ff @(posedge clk)
  for (int p = 0; p < 2; p++) begin
    f_re[p][0] <= s02_re[p] + s13_re[p];  f_im[p][0] <= s02_im[p] + s13_im[p];
    f_re[p][1] <= d02_re[p] + d13_im[p];  f_im[p][1] <= d02_im[p] - d13_re[p];
    f_re[p][2] <= s02_re[p] - s13_re[p];  f_im[p][2] <= s02_im[p] - s13_im[p];
    f_re[p][3] <= d02_re[p] - d13_im[p];  f_im[p][3] <= d02_im[p] + d13_re[p];
  end

// stages 3-5: W_8^q * B_q
//   q1: ((Br + Bi) + j(Bi - Br)) / sqrt2      q2: Bi - j Br
//   q3: ((Bi - Br) - j(Br + Bi)) / sqrt2      q0: B
logic signed [ZW+2:0]    t_re [4], t_im [4];
logic signed [ZW+2+CW:0] m_re [4], m_im [4];
logic signed [ZW+2:0]    r_re [4], r_im [4];
logic signed [ZW+1:0]    a_re [3][4], a_im [3][4];

localparam logic signed [ZW+2+CW:0] RND = (ZW+3+CW)'(1) <<< (CW-2);

always_ff @(posedge clk) begin
  t_re[0] <= f_re[1][0];                 t_im[0] <= f_im[1][0];
  t_re[1] <= f_re[1][1] + f_im[1][1];    t_im[1] <= f_im[1][1] - f_re[1][1];
  t_re[2] <= f_im[1][2];                 t_im[2] <= -f_re[1][2];
  t_re[3] <= f_im[1][3] - f_re[1][3];    t_im[3] <= -(f_re[1][3] + f_im[1][3]);

  for (int q = 0; q < 4; q++) begin
    if (q == 1 || q == 3) begin
      m_re[q] <= t_re[q] * C;
      m_im[q] <= t_im[q] * C;
      r_re[q] <= (ZW+3)'((m_re[q] + RND) >>> (CW-1));
      r_im[q] <= (ZW+3)'((m_im[q] + RND) >>> (CW-1));
    end else begin
      m_re[q] <= t_re[q];
      m_im[q] <= t_im[q];
      r_re[q] <= (ZW+3)'(m_re[q]);
      r_im[q] <= (ZW+3)'(m_im[q]);
    end
    a_re[0][q] <= f_re[0][q];  a_im[0][q] <= f_im[0][q];
    a_re[1][q] <= a_re[0][q];  a_im[1][q] <= a_im[0][q];
    a_re[2][q] <= a_re[1][q];  a_im[2][q] <= a_im[1][q];
  end
end

// stage 6
always_ff @(posedge clk)
  for (int q = 0; q < 4; q++) begin
    x_re[q] <= a_re[2][q] + r_re[q];
    x_im[q] <= a_im[2][q] + r_im[q];
  end

endmodule


/** D-cycle delay line (shift register; maps to SRLs). */
module zcu216_delay #(
  parameter int W = 1,
  parameter int D = 1
) (
  input  logic         clk,
  input  logic [W-1:0] d,
  output logic [W-1:0] q
);

if (D == 0) begin : g_wire
  assign q = d;
end else begin : g_sr
  logic [W-1:0] r [D] = '{default: '0};
  always_ff @(posedge clk) begin
    r[0] <= d;
    for (int i = 1; i < D; i++) r[i] <= r[i-1];
  end
  assign q = r[D-1];
end

endmodule
