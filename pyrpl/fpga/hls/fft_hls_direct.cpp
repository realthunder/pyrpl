// DIF twiddle factor W_N^k = exp(-j 2π k/N), read from the precomputed ROM
// (twid_re_1/twid_im_1 = cos(2πk/N)/-sin(2πk/N), index k in [0, N/SSR) here).
// ROM lookup instead of on-the-fly CORDIC: far less logic, relaxing the
// route-bound pll_ser_clk paths. twid_lut_t matches cfixed_twid_t (ap_fixed<18,2>).
#if FFT_SSR >= 2
static inline cfixed_twid_t get_twiddle(int k) {
#pragma HLS INLINE
    cfixed_twid_t w;
    w.real(twid_re_1[k]);
    w.imag(twid_im_1[k]);
    return w;
}
#endif

#if FFT_SSR == 4
// Row-2 twiddle W_N^{2k} for the SSR=4 stage-2 butterflies. The ROM stores
// W_N^{2k} as twid_re_2/twid_im_2[k] (k in [0, N/4)), so this is a direct lookup
// rather than indexing twid_re_1 at 2*i (which is out of range for SSR=4).
static inline cfixed_twid_t get_twiddle2(int k) {
#pragma HLS INLINE
    cfixed_twid_t w;
    w.real(twid_re_2[k]);
    w.imag(twid_im_2[k]);
    return w;
}
#endif

#if FFT_SSR == 8
// Per-row twiddle accessors for the SSR=8 output stage. Row r stores W_N^{r*k}
// (twid_re_r/twid_im_r[k], k in [0, N/8)); sub-FFT lane r multiplies A_r by it.
static inline cfixed_twid_t get_twiddle_row(int row, int k) {
#pragma HLS INLINE
    cfixed_twid_t w;
    switch (row) {
        case 1: w.real(twid_re_1[k]); w.imag(twid_im_1[k]); break;
        case 2: w.real(twid_re_2[k]); w.imag(twid_im_2[k]); break;
        case 3: w.real(twid_re_3[k]); w.imag(twid_im_3[k]); break;
        case 4: w.real(twid_re_4[k]); w.imag(twid_im_4[k]); break;
        case 5: w.real(twid_re_5[k]); w.imag(twid_im_5[k]); break;
        case 6: w.real(twid_re_6[k]); w.imag(twid_im_6[k]); break;
        default:w.real(twid_re_7[k]); w.imag(twid_im_7[k]); break;
    }
    return w;
}

// Multiply by W_8^2 = -j: (a + jb) -> (b - ja). Pure wiring, no multiplier.
static inline cfixed_t mul_neg_j(cfixed_t d) {
#pragma HLS INLINE
    cfixed_t r;
    r.real( d.imag());
    r.imag(-d.real());
    return r;
}

// Constant 8th-root twiddles for the radix-8 sub-DFT butterfly network.
// W_8^1 = (√2/2)(1 - j),  W_8^3 = (√2/2)(-1 - j).  W_8^0/2 are handled as
// pass-through / mul_neg_j, so only these two need a real complex multiply.
static const double SQRT1_2 = 0.70710678118654752;
static inline cfixed_twid_t w8_1() {
#pragma HLS INLINE
    cfixed_twid_t w; w.real( SQRT1_2); w.imag(-SQRT1_2); return w;
}
static inline cfixed_twid_t w8_3() {
#pragma HLS INLINE
    cfixed_twid_t w; w.real(-SQRT1_2); w.imag(-SQRT1_2); return w;
}
#endif

// CORDIC vectoring-mode magnitude (default; ported from fft_ssr_native.cpp). Selected
// unless USE_APPROXIMATION is defined, in which case the alpha-max-beta-min
// approximation below is used. Operates on the sub-FFT output component fixed_out_t
// (widened in unscaled mode). cord_t carries +2 integer bits of CORDIC growth headroom
// and +14 fractional bits for <0.02% gain precision.
#ifndef USE_APPROXIMATION
// +2 integer bits of CORDIC growth headroom, +8 fractional bits below the input LSB
// for iteration/gain precision (ample for CORDIC_ITER<=~12; keeps the magnitude's
// INTERNAL_W-1 fractional accuracy). Narrower than IMPL=4's +14 to save pipeline FF.
typedef ap_fixed<OUT_W + 8, OUT_I + 2> cord_t;
static cord_t cordic_magnitude_raw(fixed_out_t re_in, fixed_out_t im_in) {
#pragma HLS INLINE
    cord_t x = (re_in < 0) ? cord_t(-re_in) : cord_t(re_in);
    cord_t y = (im_in < 0) ? cord_t(-im_in) : cord_t(im_in);
    const cord_t cordic_gain = 0.607252935;
    for (int i = 0; i < CORDIC_ITER; i++) {
#pragma HLS PIPELINE II=1
        cord_t xs = x >> i;
        cord_t ys = y >> i;
        if (y > 0) { x = x + ys; y = y - xs; }
        else       { x = x - ys; y = y + xs; }
    }
    return x * cordic_gain;
}
#endif

// Magnitude of a sub-FFT output sample -> DSZ-bit unsigned.
//   scaled  : input in [-1,1), |z| in [0,~1.5) -> DSZ-bit fixed with 2 integer bits
//             (unchanged from the original scaled build).
//   unscaled: |z| spans [0,~1.5*2^SUB_NFFT); narrow to DSZ by keeping the low bits
//             (LSB = 2^-(INTERNAL_W-1)) and saturating the top — the FFT_SCALED=2
//             "saturating" convention, matching IMPL=4's magnitude() guard.
static inline ap_uint<DSZ> magnitude(cfixed_out_t v) {
#pragma HLS INLINE
#ifdef USE_APPROXIMATION
    // Alpha-max-beta-min: |z| ≈ max(|re|,|im|) + 3/8·min(|re|,|im|)
    typedef ap_fixed<OUT_W + 1, OUT_I + 1> wider_t;
    wider_t re = v.real() < 0 ? (wider_t)(-v.real()) : (wider_t)v.real();
    wider_t im = v.imag() < 0 ? (wider_t)(-v.imag()) : (wider_t)v.imag();
    wider_t mx = (re > im) ? re : im;
    wider_t mn = (re > im) ? im : re;
    // Register the min-approximation add (latency=1) to split the CARRY4 chain
    // (compare -> add -> add -> cast) that otherwise binds pll_ser_clk.
    wider_t mn_approx = (mn >> 2) + (mn >> 3);
#pragma HLS BIND_OP variable=mn_approx op=add latency=1
    wider_t mag = mx + mn_approx;
#else
    cord_t mag = cordic_magnitude_raw(v.real(), v.imag());
#endif

#ifdef FFT_UNSCALED
    // Saturating narrow: reinterpret |z|'s bit pattern as an unsigned integer
    // (value scaled by 2^(INTERNAL_W-1), i.e. OUT_W-OUT_I = INTERNAL_W-1 frac bits),
    // keep the low DSZ bits, saturate above. == IMPL=4 magnitude() guard.
    const int MAGBITS = OUT_W + 2;
    ap_ufixed<MAGBITS, OUT_I + 2> umag = mag;
    ap_uint<MAGBITS> bits = umag.range(MAGBITS - 1, 0);
    return (bits >> DSZ) ? ap_uint<DSZ>(-1) : ap_uint<DSZ>(bits);
#else
    ap_ufixed<DSZ, 2> out = mag;
    return out.range(DSZ-1, 0);
#endif
}

// Convert a raw signed ASZ-bit ADC sample to the internal ap_fixed<INTERNAL_W,1> value
// in [-1,1) by MSB-aligning it into the top ASZ bits. A plain value cast
// (ap_fixed<INTERNAL_W,1>(raw)) WRAPS any |raw|>=1 — i.e. it zeroes the whole 14-bit
// ADC input — which silently broke the FFT (csim: every tone collapsed to bin 0).
// Matches fft_ip_ssr.cpp's input handling.
static inline ap_fixed<INTERNAL_W,1> adc_to_fixed(ap_int<ASZ> raw) {
#pragma HLS INLINE
    ap_fixed<INTERNAL_W,1> v = 0;
    v.range(INTERNAL_W-1, INTERNAL_W-ASZ) = raw;
    return v;
}

// hls::fft (2020.1) takes C arrays, not streams, so each FFT needs an array feed
// and drain. These run as processes in the TOP-level DATAFLOW region alongside
// hls::fft — matching the canonical Xilinx FFT example's two-level dataflow
// (fft_top → hls::fft). Wrapping them in an intermediate fft_serial() function
// adds a third dataflow level that corrupts hls::fft's internal xn_cp/xk_cp
// buffers (they degrade to ROM/BRAM and the stream-based FFT wrapper is wired to
// memory ports), so the feed/fft/drain are inlined into the top function below.
// sub_size = 2^sub_nfft is the runtime sub-FFT length (<= SUB_SIZE). The config
// word is programmed here: direction, the runtime NFFT, and the matching scaling
// schedule. The LogiCORE then transforms exactly the first sub_size elements.
static void fft_feed(hls::stream<cfixed_t> &in,
                     cfixed_t xn[SUB_SIZE],
                     fft_config_t *cfg,
                     int sub_size,
                     unsigned sub_nfft) {
    cfg->setDir(1);
#ifdef FFT_RUNTIME_NFFT
    cfg->setNfft(sub_nfft);
  #ifndef FFT_UNSCALED
    // Unscaled has no per-stage schedule; setSch()->checkSch() errors unless scaled.
    cfg->setSch(SCALE_SCHED_LUT.v[sub_nfft]);
  #endif
#else
    (void)sub_nfft;
  #ifndef FFT_UNSCALED
    cfg->setSch(SCALE_SCHED);
  #endif
#endif
    for (int i = 0; i < RT_N(sub_size, SUB_SIZE); i++) {
#pragma HLS PIPELINE II=1
#pragma HLS LOOP_TRIPCOUNT min=8 max=SUB_SIZE
        xn[i] = in.read();
    }
}

static void fft_drain(cfixed_out_t xk[SUB_SIZE],
                      hls::stream<cfixed_out_t> &out,
                      fft_status_t *sts,
                      int sub_size) {
    (void)*sts;  // overflow status unused
    for (int i = 0; i < RT_N(sub_size, SUB_SIZE); i++) {
#pragma HLS PIPELINE II=1
#pragma HLS LOOP_TRIPCOUNT min=8 max=SUB_SIZE
        out.write(xk[i]);
    }
}

// ============================================================
// SSR = 1  (single serial FFT, no butterfly stage)
// ============================================================
#if FFT_SSR == 1

static void input_ssr1(hls::stream<axis_in_t> &s_axis,
                       hls::stream<cfixed_t>  &out,
                       int n) {
    for (int i = 0; i < RT_N(n, FFT_SIZE); i++) {
#pragma HLS PIPELINE II=1
#pragma HLS LOOP_TRIPCOUNT min=8 max=FFT_SIZE
        ap_int<ASZ> raw = s_axis.read().data.range(ASZ-1, 0);
        cfixed_t v;
        v.real(adc_to_fixed(raw));
        v.imag(0);
        out.write(v);
    }
}

static void output_ssr1(hls::stream<cfixed_t>   &in,
                        hls::stream<axis_out_t> &m_axis,
                        int n) {
    for (int i = 0; i < RT_N(n, FFT_SIZE); i++) {
#pragma HLS PIPELINE II=1
#pragma HLS LOOP_TRIPCOUNT min=8 max=FFT_SIZE
        axis_out_t pkt;
        pkt.data.range(DSZ-1, 0) = magnitude(in.read());
        pkt.last = (i == RT_N(n, FFT_SIZE) - 1);
        m_axis.write(pkt);
    }
}

#endif // FFT_SSR == 1

