// INTERNAL_W: internal FFT datapath width (the fixed-point precision carried through
// the butterflies/twiddles), NOT an integer-bit count. Wider = lower quantization
// floor = more small-signal dynamic range, at a cost of FFT-core DSP/BRAM. Override
// with -DINTERNAL_W (build knob FFT_INTERNAL_W). Default 16.
// MUST be a multiple of 8: hls::fft byte-rounds the I/O datapath to ceil(W/8)*8 and
// the cfixed_t array type must match it, so 16/24/32 are the only usable values — a
// non-multiple (e.g. 20) fails to compile (no matching hls::fft overload) and would
// round up to the next byte anyway (no BRAM saving vs the rounded width).
#ifndef INTERNAL_W
#define INTERNAL_W 16
#endif
static_assert(INTERNAL_W % 8 == 0,
    "INTERNAL_W (FFT_INTERNAL_W) must be a multiple of 8 (hls::fft byte-rounds the datapath; use 16/24/32).");
// CORDIC vectoring-mode magnitude iterations (used unless USE_APPROXIMATION is set).
// Build knob FFT_CORDIC_ITER (default 10): fewer iterations = smaller pipeline (less
// FF/LUT) at lower magnitude accuracy (~iter bits). 10 is ample for peak detection;
// 16 = full precision but ~1.6x the CORDIC area. Below ~5 the approx is better.
#ifndef CORDIC_ITER
#define CORDIC_ITER 10
#endif
static const int TWID_W = 18;  // twiddle factor precision

typedef std::complex<ap_fixed<INTERNAL_W, 1>>   cfixed_t;
typedef std::complex<ap_fixed<TWID_W, 2>> cfixed_twid_t;
typedef ap_fixed<INTERNAL_W + TWID_W + 1, 4>   fixed_mul_t;  // scalar multiply accumulator

// Sub-FFT output sample type. hls::fft byte-rounds the datapath and fixes the xn/xk
// element types: input = ap_fixed<byteround(input_width),1>, output =
// ap_fixed<byteround(output_width), byteround(output_width)-input_width+1> (see the
// 1-channel fixed-point overload in hls_fft.h). cfixed_out_t MUST match that exactly.
//   scaled:   output_width = INTERNAL_W           -> OUT_W = INTERNAL_W, OUT_I = 1
//             (identical to cfixed_t; existing scaled datapath unchanged).
//   unscaled: output_width = byteround(INTERNAL_W + SUB_NFFT + 1) (the hls::fft golden
//             value; grows over the N/SSR sub-transform); OUT_I integer, INTERNAL_W-1 frac.
#ifdef FFT_UNSCALED
static const int OUT_W = (((INTERNAL_W + SUB_NFFT + 1) + 7) / 8) * 8;
#else
static const int OUT_W = (((INTERNAL_W) + 7) / 8) * 8;
#endif
static const int OUT_I = OUT_W - INTERNAL_W + 1;
typedef ap_fixed<OUT_W, OUT_I>     fixed_out_t;
typedef std::complex<fixed_out_t>  cfixed_out_t;

// ============================================================
// LogiCORE FFT configuration
// ============================================================

// Avnet per-stage scaling schedule: alternating "10"/"01" + "11" final
// Prevents overflow while maximising precision for a given sub-FFT depth.
static constexpr int scale_sched(int n) {
    int ibits = (n + 1) / 2;
    int bits  = (n % 2 == 0) ? 2 : 1;               // "10" or "01"
    for (int i = 1; i < ibits - 1; i++) bits = (bits << 2) | 2; // append "10"
    bits = (bits << 2) | 3;                           // append "11"
    return bits;
}

// Fixed-length build: a single compile-time schedule for the max NFFT.
static const int SCALE_SCHED = scale_sched(SUB_NFFT);

#ifdef FFT_RUNTIME_NFFT
// Per-size scaling schedule table, indexed by the runtime sub-FFT exponent.
// With run-time configurable length the schedule must match the configured NFFT
// (a smaller transform uses fewer butterfly stages), so we cannot bake in a
// single SCALE_SCHED — we look it up by sub_nfft at frame start. Filled at
// compile time (constexpr) into a ROM; scale_sched(n) is unchanged.
struct sched_lut_t {
    int v[SUB_NFFT + 1];
    constexpr sched_lut_t() : v() {
        for (int n = 0; n <= SUB_NFFT; n++) v[n] = scale_sched(n);
    }
};
static const sched_lut_t SCALE_SCHED_LUT;
#endif

// ---- Build-knob helpers: collapse to compile-time constants when fixed-length.
// RT_N(rt, konst):    loop trip count / size      — runtime value vs constant
// RT_NFFT(rt, konst): an nfft-like exponent        — runtime value vs constant
// RT_TW(i, sh):       twiddle ROM index            — strided vs direct
// When FFT_RUNTIME_NFFT is unset every site folds to the original constant so the
// generated RTL (and LUT/timing) is identical to the fixed-length design; the
// runtime args passed in are then dead and optimised away.
#ifdef FFT_RUNTIME_NFFT
  #define RT_N(rt, konst)    (rt)
  #define RT_NFFT(rt, konst) (rt)
  #define RT_TW(i, sh)       ((i) << (sh))
#else
  #define RT_N(rt, konst)    (konst)
  #define RT_NFFT(rt, konst) (konst)
  #define RT_TW(i, sh)       (i)
#endif

struct fft_params_t : hls::ip_fft::params_t {
#ifdef FFT_NATURAL_ORDER
    // natural_order: the LogiCORE sub-FFTs add an internal reorder buffer so bins
    // stream out in spectral order. Required when the peak detector interpolates
    // (peak_frac != 0) — sub-bin interp reads adjacent bins, only adjacent in natural
    // order. output_ssr2/4 then emit beat b = {X[FSSR·b .. FSSR·b+FSSR-1]} (natural),
    // and fft_proc.sv uses non-bit-reversed readback addressing to match. Costs one
    // reorder buffer per sub-FFT (extra BRAM) vs bit_reversed_order.
    static const unsigned ordering_opt       = hls::ip_fft::natural_order;
#else
    // bit_reversed_order costs no internal reorder buffer in LogiCORE.
    // The output permutation is handled by BRAM addressing in fft_proc.sv.
    static const unsigned ordering_opt       = hls::ip_fft::bit_reversed_order;
#endif
    static const unsigned max_nfft           = SUB_NFFT;
    static const unsigned input_width        = INTERNAL_W;
#ifdef FFT_UNSCALED
    // Unscaled: no per-stage /2; hls::fft requires output_width =
    // byteround(input_width + max_nfft + 1) == OUT_W (see hls_fft.h golden check).
    static const unsigned scaling_opt        = hls::ip_fft::unscaled;
    static const unsigned output_width       = OUT_W;
#else
    static const unsigned scaling_opt        = hls::ip_fft::scaled;
    static const unsigned output_width       = INTERNAL_W;
#endif
    static const unsigned status_width       = 8;
#ifdef FFT_RUNTIME_NFFT
    // Run-time configurable transform length (build knob FFT_RUNTIME_NFFT): the
    // generated LogiCORE accepts an NFFT field in the config word, so one
    // synthesized core (built for max_nfft = SUB_NFFT) can run any 2^n sub-FFT
    // with n <= SUB_NFFT. The surrounding dataflow loops are bounded by the
    // runtime size below. Mirrors IMPL==1's run_time_configurable_transform_length
    // xfft. Costs ~2700 LUTs vs the fixed-length build, so it is opt-in.
    static const bool     has_nfft           = true;
    // config word = NFFT field (low 8 bits, padded) + per-stage scaling schedule
    // (2 bits/stage, scaled only) + 1 direction bit, byte-rounded. The +8 is the
    // NFFT field. Unscaled has no scaling schedule, so those 2*ceil/2 bits drop out
    // (else checkConfig errors: the wrapper only counts schedule bits when scaled).
  #ifdef FFT_UNSCALED
    static const unsigned config_width       = ((1+8+7)/8)*8;
  #else
    static const unsigned config_width       = ((2*((SUB_NFFT+1)/2)+1+8+7)/8)*8;
  #endif
#else
    // Fixed-length: NFFT baked in at max_nfft, no config NFFT field.
  #ifdef FFT_UNSCALED
    static const unsigned config_width       = ((1+7)/8)*8;
  #else
    static const unsigned config_width       = ((2*((SUB_NFFT+1)/2)+1+7)/8)*8;
  #endif
#endif
    static const unsigned phase_factor_width = TWID_W;
    static const unsigned stages_block_ram   = (SUB_NFFT < 10) ? 0 : SUB_NFFT - 9;
#ifdef FFT_MULT_LUT
    // DSP->LUT trade: implement the twiddle complex multipliers and butterflies
    // in CLB/LUT logic instead of XtremeDSP. Frees DSP48 (relieves the ~98% DSP
    // wall at SSR=4) at the cost of more LUTs and lower per-mult Fmax. Default
    // (unset) keeps DSP-based mults: complex_mult_type=use_mults_resources,
    // butterfly_type=use_xtremedsp.
    static const unsigned complex_mult_type = hls::ip_fft::use_luts;
    static const unsigned butterfly_type    = hls::ip_fft::use_luts;
#endif
};

