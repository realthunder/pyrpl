#!/usr/bin/env python3
"""Write zcu216/clk104_tables.h: the CLK104 register sequences that zcu216/clk104
sends, copied from AMD's xrfclk library (embeddedsw, MIT licence) for the ZCU216:

  LMK04828  "250M_PL_125M_SYSREF_10M"   LMK_CKin[1]   (128 writes)
  LMX2594   "LMX2594_REF-250M__2500M"   LMX2594[7]    (116 writes, both LMXs)

  python3 zcu216/gen_clk104_tables.py [<xrfclk src dir>]
"""
import os, re, sys

SRC = (sys.argv[1] if len(sys.argv) > 1 else
       '/tools/Xilinx/2025.2/data/embeddedsw/XilinxProcessorIPLib/drivers/'
       'board_common_v2_0/src/rfclk/src')


def zcu216_part(path):
    """The #else (ZCU216) half of a conf header."""
    t = open(path).read()
    return t[t.index('#else'):]


def array(text, name):
    """Rows of the C array `name` as lists of ints."""
    body = text[text.index(name):]
    body = body[body.index('{') + 1:]
    rows, depth, cur = [], 0, ''
    for ch in body:
        if ch == '{':
            depth += 1
            cur = ''
        elif ch == '}':
            if depth == 0:
                break
            depth -= 1
            rows.append([int(x, 16) for x in re.findall(r'0x[0-9A-Fa-f]+', cur)])
        elif depth == 1:
            cur += ch
    return rows


def names(text, name):
    body = text[text.index(name):]
    body = body[:body.index('};')]
    return re.findall(r'"([^"]+)"', body)


def main():
    lmk_t = zcu216_part(os.path.join(SRC, 'xrfclk_LMK_conf.h'))
    lmx_t = zcu216_part(os.path.join(SRC, 'xrfclk_LMX_conf.h'))
    lmk_names = names(lmk_t, 'LMK_FREQ_LIST[')
    dac_names = names(lmx_t, 'DAC_FREQ_LIST[')
    lmk_i, lmx_i = lmk_names.index('250M_PL_125M_SYSREF_10M'), dac_names.index('LMX2594_REF-250M__2500M')
    lmk = array(lmk_t, 'const u32 LMK_CKin[')[lmk_i]
    lmx = array(lmx_t, 'const u32 LMX2594[')[lmx_i]
    assert len(lmk) == 128 and len(lmx) == 116, (len(lmk), len(lmx))

    def rows(v):
        return '\n'.join('    ' + ', '.join('0x%06x' % x for x in v[i:i + 6]) + ','
                         for i in range(0, len(v), 6))

    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'clk104_tables.h')
    with open(out, 'w') as f:
        src = SRC.split('drivers/')[-1].rstrip('/')
        f.write(f'''/* Generated by zcu216/gen_clk104_tables.py from AMD's xrfclk (embeddedsw,
 * MIT licence): the ZCU216 tables in {src}/
 * xrfclk_LMK_conf.h and xrfclk_LMX_conf.h. 24-bit SPI words, sent in order.
 * Do not edit. */

/* LMK04828 "{lmk_names[lmk_i]}" (LMK_CKin[{lmk_i}]) */
static const unsigned lmk_250m[{len(lmk)}] = {{
{rows(lmk)}
}};

/* LMX2594 "{dac_names[lmx_i]}" (LMX2594[{lmx_i}]): 2.5 GHz from 250 MHz */
static const unsigned lmx_2500m[{len(lmx)}] = {{
{rows(lmx)}
}};
''')
    print('wrote', out)


if __name__ == '__main__':
    main()
