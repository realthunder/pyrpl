    def _dma_configure_from_fpga(self):
        """Reconfigure the UDP unpacker from the FPGA packet-format descriptor.

        Reads the self-describing descriptor registers (0x170/0x194) so the host
        layout always matches the running bitstream. Called before the receive
        thread starts; warns (but proceeds) on a version it does not recognise.
        """
        version = self.dma_fmt_version
        if version not in self._DMA_FMT_VERSIONS_SUPPORTED:
            self._logger.warning(
                "DMA packet-format version %d not in supported %s; decoding may be "
                "wrong. Update pyrpl to match the FPGA bitstream.",
                version, self._DMA_FMT_VERSIONS_SUPPORTED)
        self._dma_udp_client.configure(
            fsz=self.dma_fmt_fsz,
            frac=self.dma_fmt_frac,
            hsz=self.dma_fmt_hsz,
            hist_block_size=self.dma_block_size,
            max_interval=self.dma_max_interval,
            seq_bits=self.dma_fmt_seq_bits,
            # v5/v6 (and the azimuth v9/v10) append a value word (raw peak
            # amplitudes, DSZ bits each, reg 0x34) per point; the client
            # derives reflectivity from it.
            dsz=self.fft_data_width,
            intensity=version in (5, 6, 9, 10),
            # Azimuth variants: cell = {tick, mems[msw-1:0]} (descriptor 0x1A4).
            msw=self.dma_az_msw if self._dma_azimuth_cap else None,
        )

    def _ownership_changed(self, old, new):
        """
        If the scope was in continuous mode when slaved, it has to stop!!
        """
        if new is not None:
            self.stop()
        # The DMA multicast receiver is tied to the acquisition *session*, not
        # the per-trace state machine: stop() is called once per trace (e.g. by
        # Lidar._start_trace_acquisition) to re-arm the scope, so tearing the
        # socket+thread down there churned it every frame. Tear it down only on
        # a genuine ownership change instead — scope freed at the end of a run,
        # or slaved away by another module.
        self._dma_udp_client.stop()

