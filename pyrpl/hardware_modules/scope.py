class DurationProperty(SelectProperty):
    def get_value(self, obj):
        return obj.sampling_time * float(obj.data_length)

    def validate_and_normalize(self, obj, value):
        # gets next-higher value
        value = float(value)
        options = self.options(obj).keys()
        try:
            return min([opt for opt in options if opt >= value],
                   key=lambda x: abs(x - value))
        except ValueError:
            obj._logger.info("Selected duration is longer than "
                             "physically possible with the employed hardware. "
                             "Picking longest-possible value %s. ",
                             max(options))
            return max(options)

    def set_value(self, obj, value):
        """sets returns the duration of a full scope sequence the rounding
        makes sure that the actual value is longer or equal to the set value"""
        obj.sampling_time = float(value) / obj.data_length


class SamplingTimeProperty(SelectProperty):
    def get_value(self, obj):
        return 8e-9 * float(obj.decimation)

    def validate_and_normalize(self, obj, value):
        # gets next-lower value
        value = float(value)
        options = self.options(obj).keys()
        try:
            return min([opt for opt in options if opt <= value],
                   key=lambda x: abs(x - value))
        except ValueError:
            obj._logger.info("Selected sampling time is shorter than "
                             "physically possible with the employed hardware. "
                             "Picking shortest-possible value %s. ",
                             min(options))
            return min(options)

    def set_value(self, instance, value):
        """sets or returns the time separation between two subsequent
        points of a scope trace the rounding makes sure that the actual
        value is shorter or equal to the set value"""
        instance.decimation = float(value) / 8e-9


class DmaMaxIntervalProperty(FloatProperty):
    """FloatProperty that also pushes the new value into a running DMA UDP client,
    so the publish cadence applies live (no acquisition restart needed).

    Negative values are a MULTIPLIER of the scan's theoretical frame period
    (-2 = a fallback publish every two raster periods, for a stalled frame
    counter). The scope cannot derive that period itself, so a negative value
    is only STORED here — the lidar layer (pointcloud._sync_dma_parse_rate)
    converts it to seconds from the measured scan rate and pushes the result
    straight to the client."""
    def set_value(self, obj, val):
        super(DmaMaxIntervalProperty, self).set_value(obj, val)
        client = getattr(obj, '_dma_udp_client', None)
        if client is not None and float(val) >= 0:
            client.configure(max_interval=float(val))
        return val


class DmaUnicastProperty(BoolProperty):
    """BoolProperty selecting how the host receives the DMA point cloud:
    True  = unicast (monitor_server sends straight to this host; default),
    False = join the multicast group. Unicast avoids multicast interface-
    selection problems on multi-homed hosts (e.g. Windows with several virtual
    NICs). Changing it updates the UDP client and, if a receiver is already
    running, stops it so the next acquisition restarts in the new mode (the
    (re)start is gated in Scope._start_trace_acquisition)."""
    def set_value(self, obj, val):
        super(DmaUnicastProperty, self).set_value(obj, val)
        client = getattr(obj, '_dma_udp_client', None)
        if client is not None and client._unicast != bool(val):
            client._unicast = bool(val)
            client.stop()  # restarted in the new mode on the next acquisition
        return val


class _AzModulusRegister(IntRegister):
    """enc_az_modulus with a bound from the bitstream: the DMA cell's tick field
    is TKW = HSZ - MSW bits (descriptor 0x1A4), and the encoder latches ticks
    >= T as T itself, so T must fit that field or the overflow bucket aliases
    into the frame. Clamps with a warning instead of writing an unusable T."""
    def validate_and_normalize(self, obj, value):
        value = super(_AzModulusRegister, self).validate_and_normalize(obj, value)
        try:
            tkw = int(obj.dma_az_tkw) if obj._dma_azimuth_cap else 0
        except Exception:
            tkw = 0
        if tkw and value > (1 << tkw) - 1:
            obj._logger.warning(
                "enc_az_modulus %d exceeds the azimuth cell tick field "
                "(%d bits); clamping to %d", value, tkw, (1 << tkw) - 1)
            value = (1 << tkw) - 1
        return value


